#!/bin/bash
# SPDX-License-Identifier: GPL-2.0-only
# Arch's own GRUB next to Fedora's (docs/plan-arch-boot.md, part B), tested
# without touching the current boot. Adds only our own things: \EFI\arch\
# (grubaa64.efi), /grub/ on sda4 (modules + grub.cfg; Fedora's is /grub2/),
# \EFI\book4-el2-arch\ (a copy of the EL2 shell folder whose startup.nsh
# starts \EFI\arch\grubaa64.efi) and a firmware entry for it placed LAST in
# the boot order. Nothing of Fedora's or of the current EL2 folder changes.
#
#   bash install/arch/arch-grub.sh install   GRUB, menu, EL2 test folder, firmware entry
#   bash install/arch/arch-grub.sh menu      regenerate /grub/grub.cfg from today's menu
#   bash install/arch/arch-grub.sh next      boot the Arch GRUB entry ONCE at the next boot
#   bash install/arch/arch-grub.sh status
#   bash install/arch/arch-grub.sh undo      remove the entry and our folders (not Fedora's)
#
# The menu, for now, is today's menu (Fedora's static \EFI\fedora\grub.cfg,
# written by 99-book4-devicetree.install) with the Windows entry using this
# GRUB's own chainloader; the generator moves to Arch in step B3. Arch's
# GRUB 2.16 has cutmem (mmap), devicetree (fdt) and chainloader (chain).
set -euo pipefail
LABEL="Book4 EL2 (Arch GRUB)"
OLD=EFI/book4-el2; NEW=EFI/book4-el2-arch
SHELLARGS="Shellaa64.efi -delay 0"
esp=/efi
[ -e /etc/arch-release ] || { echo "Run this on Arch." >&2; exit 1; }
if findmnt -rn -S /dev/sda4 >/dev/null; then echo "error: /dev/sda4 (/boot) is mounted; unmount it first" >&2; exit 1; fi
sudo -v
entry() { sudo efibootmgr | awk -v l="$LABEL" '/^Boot[0-9A-F][0-9A-F][0-9A-F][0-9A-F]/ {
    n = substr($0, 5, 4); t = substr($0, 10); sub(/^\* ?/, "", t); sub(/^ /, "", t); sub(/\t.*/, "", t)
    if (t == l) { print n; exit } }'; }
mountboot() { b=$(mktemp -d); sudo mount /dev/sda4 "$b"; }
umountboot() { sync; sudo umount "$b"; rmdir "$b"; }

menu() {  # $b mounted
    local src=$esp/EFI/fedora/grub.cfg tmp; tmp=$(mktemp)
    sudo test -f "$src" || { echo "error: $src missing" >&2; return 1; }
    { echo "# Arch GRUB (install/arch/arch-grub.sh menu): today's menu from \\EFI\\fedora\\grub.cfg,"
      echo "# Windows through this GRUB's own chainloader. Regenerated by 'menu'; do not edit."
      sudo cat "$src" | sed -e '/^# Samsung Galaxy Book4 Edge 14" - regenerated/d' -e '/^# on every kernel add\/remove/d' \
          -e 's|^    insmod (\$winesp)/EFI/book4/arm64-efi/chain.mod$|    insmod chain|' \
          -e '/# Fedora.s signed arm64 GRUB lacks the chainloader/,/# chain.mod this hook keeps on the ESP/d'
    } > "$tmp"
    grep -q '^  cutmem 0x8800000000 0x8fffffffff' "$tmp" || { echo "error: the menu lost the cutmem line" >&2; rm -f "$tmp"; return 1; }
    grep -q 'source (\$bootdev)/book4-extra.cfg' "$tmp" || { echo "error: the menu lost the test entries" >&2; rm -f "$tmp"; return 1; }
    sudo install -D -m 644 "$tmp" "$b/grub/grub.cfg"; rm -f "$tmp"
    echo "   /grub/grub.cfg: $(grep -c '^menuentry' "$b/grub/grub.cfg") entries + book4-extra.cfg"
}

case "${1:-}" in
install)
    command -v grub-install >/dev/null || { echo "error: grub missing (sudo pacman -S grub)" >&2; exit 1; }
    [ -n "$(ls /sys/firmware/efi/efivars 2>/dev/null | head -1)" ] || { echo "error: no EFI variables" >&2; exit 1; }
    sudo test -e "$esp/$OLD/Shellaa64.efi" || { echo "error: $esp/$OLD missing" >&2; exit 1; }
    echo "== 1. grub-install (\\EFI\\arch\\, /grub on sda4, no firmware entry)"
    mountboot
    sudo grub-install --target=arm64-efi --efi-directory="$esp" --boot-directory="$b" \
        --bootloader-id=arch --no-nvram 2>&1 | sed 's/^/   /'
    sudo test -e "$esp/EFI/arch/grubaa64.efi" || { umountboot; echo "error: \\EFI\\arch\\grubaa64.efi not written" >&2; exit 1; }
    echo "== 2. menu"; menu; umountboot
    echo "== 3. EL2 test folder \\$NEW"
    sudo mkdir -p "$esp/$NEW"
    for f in Shellaa64.efi qebspilaa64.efi slbounce.efi tcblaunch.exe; do sudo install -m 644 "$esp/$OLD/$f" "$esp/$NEW/$f"; done
    sudo sed -e 's|\\EFI\\fedora\\grubaa64\.efi|\\EFI\\arch\\grubaa64.efi|g' -e 's|\\EFI\\book4-el2\\|\\EFI\\book4-el2-arch\\|g' \
        -e 's|Fedora.s GRUB|Arch GRUB|g' "$esp/$OLD/startup.nsh" | sudo tee "$esp/$NEW/startup.nsh" >/dev/null
    cmds=$(sudo grep -v '^#' "$esp/$NEW/startup.nsh")   # comments may mention \EFI\fedora\
    grep -q 'EFI\\arch\\grubaa64.efi' <<<"$cmds" && ! grep -q 'EFI\\fedora' <<<"$cmds" ||
        { echo "error: the test startup.nsh does not point at Arch GRUB only" >&2; exit 1; }
    echo "== 4. firmware entry '$LABEL', last in the boot order"
    order=$(sudo efibootmgr | sed -n 's/^BootOrder: //p')
    n=$(entry); [ -z "$n" ] || sudo efibootmgr -q -b "$n" -B
    sudo efibootmgr -q --create --disk /dev/sda --part 1 --label "$LABEL" --loader "\\${NEW//\//\\}\\Shellaa64.efi" --unicode "$SHELLARGS"
    n=$(entry); [ -n "$n" ] || { echo "error: entry not created" >&2; exit 1; }
    order=$(tr ',' '\n' <<<"$order" | grep -vx "$n" | paste -sd, -)
    sudo efibootmgr -q -o "$order,$n"
    sudo efibootmgr | grep -E "^BootOrder|^BootCurrent"
    echo; echo "Done. Nothing boots differently yet. To try it once: bash install/arch/arch-grub.sh next, then reboot." ;;
menu) mountboot; menu; umountboot ;;
next)
    n=$(entry); [ -n "$n" ] || { echo "error: no '$LABEL' entry; run install first" >&2; exit 1; }
    sudo efibootmgr -q -n "$n"
    echo "BootNext = $n ($LABEL): the next boot only; the one after is the normal one."
    sudo efibootmgr | grep -E "^BootNext|^BootOrder" ;;
status)
    sudo efibootmgr | grep -E "^Boot(Current|Next|Order)|$LABEL"
    sudo ls -la "$esp/EFI/arch" "$esp/$NEW" 2>&1 | sed 's/^/   /'
    mountboot; ls "$b/grub" 2>&1 | head -5 | sed 's/^/   \/grub: /'; umountboot ;;
undo)
    n=$(entry); [ -z "$n" ] || { sudo efibootmgr -q -b "$n" -B; echo "removed Boot$n"; }
    sudo rm -rf "$esp/$NEW" "$esp/EFI/arch"
    mountboot; sudo rm -rf "$b/grub"; umountboot
    echo "removed \\$NEW, \\EFI\\arch, /grub (Fedora's GRUB untouched)" ;;
*) sed -n '3,16p' "$0"; exit 1 ;;
esac
